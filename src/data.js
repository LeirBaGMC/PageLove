function buildSeries(values) {
  const trend = {
    2019: 0.7,
    2020: 0.78,
    2021: 0.86,
    2022: 0.93,
    2023: 1,
    2024: 1.05,
    2025: 1.1,
    2026: 1.15,
  };
  const womenFactor = {
    depression: 1.28,
    anxiety: 1.24,
    eating: 1.65,
    bipolar: 1.08,
    schizophrenia: 0.92,
  };
  const menFactor = {
    depression: 0.72,
    anxiety: 0.76,
    eating: 0.35,
    bipolar: 0.92,
    schizophrenia: 1.08,
  };
  return Object.fromEntries(
    Object.keys(trend).map((year) => [
      year,
      {
        general: Object.fromEntries(
          Object.entries(values).map(([key, value]) => [
            key,
            +(value * trend[year]).toFixed(2),
          ]),
        ),
        women: Object.fromEntries(
          Object.entries(values).map(([key, value]) => [
            key,
            +(value * trend[year] * womenFactor[key]).toFixed(2),
          ]),
        ),
        men: Object.fromEntries(
          Object.entries(values).map(([key, value]) => [
            key,
            +(value * trend[year] * menFactor[key]).toFixed(2),
          ]),
        ),
      },
    ]),
  );
}

